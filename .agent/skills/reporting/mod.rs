#[async_trait]
impl Skill for ReportingSkill {
    fn name(&self) -> &str {
        "reporting"
    }
    
    fn description(&self) -> &str {
        "Generate professional security reports"
    }
    
    async fn execute(&self, args: &[String]) -> anyhow::Result<()> {
        if args.is_empty() {
            println!("Reporting Skill");
            println!("\nUsage:");
            println!("  klp report --kind <type> --output <file>");
            println!("\nReport Types:");
            println!("  --kind pentest    - Penetration test report");
            println!("  --kind system     - System audit report");
            println!("  --kind osint      - OSINT report");
            println!("  --kind full       - Comprehensive report");
            println!("\nOptions:");
            println!("  --format <fmt>    - pdf, html, md, json");
            println!("  --company <name>  - Company name");
            println!("  --author <name>   - Author name");
            println!("  --templates       - List available templates");
            return Ok(());
        }
        
        // Parse arguments
        let mut kind = "pentest";
        let mut output = "report.pdf";
        let mut format = "pdf";
        let mut company = None;
        let mut author = None;
        let mut target = None;
        
        let mut i = 0;
        while i < args.len() {
            match args[i].as_str() {
                "--kind" => {
                    if i + 1 < args.len() {
                        kind = &args[i + 1];
                        i += 1;
                    }
                }
                "--output" => {
                    if i + 1 < args.len() {
                        output = &args[i + 1];
                        i += 1;
                    }
                }
                "--format" => {
                    if i + 1 < args.len() {
                        format = &args[i + 1];
                        i += 1;
                    }
                }
                "--company" => {
                    if i + 1 < args.len() {
                        company = Some(args[i + 1].as_str());
                        i += 1;
                    }
                }
                "--author" => {
                    if i + 1 < args.len() {
                        author = Some(args[i + 1].as_str());
                        i += 1;
                    }
                }
                "--target" => {
                    if i + 1 < args.len() {
                        target = Some(args[i + 1].as_str());
                        i += 1;
                    }
                }
                "--templates" => {
                    self.list_templates();
                    return Ok(());
                }
                _ => {}
            }
            i += 1;
        }
        
        // Generate appropriate report
        match kind {
            "pentest" => {
                self.generate_pentest_report(output, format, company, author).await?;
            }
            "system" => {
                self.generate_system_report(output, format).await?;
            }
            "osint" => {
                if let Some(t) = target {
                    self.generate_osint_report(t, output).await?;
                } else {
                    println!("OSINT report requires --target");
                }
            }
            _ => {
                println!("Unknown report type: {}", kind);
            }
        }
        
        Ok(())
    }
}
